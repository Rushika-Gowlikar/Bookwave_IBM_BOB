// Helper function to calculate guaranteed dynamic delivery date strictly within 1 week (3 to 5 days, max 6 days)
export function getEstimatedDeliveryDate(offsetDays = 4, baseDate = new Date()) {
  const d = new Date(baseDate);
  const safeOffset = Math.min(Math.max(offsetDays, 2), 6); // Always 2 to 6 days (<= 1 week)
  d.setDate(d.getDate() + safeOffset);
  return d.toLocaleDateString('en-IN', { weekday: 'short', day: '2-digit', month: 'short' });
}

export function getEstimatedTentative(offsetStart = 3, offsetEnd = 5, baseDate = new Date()) {
  const d1 = new Date(baseDate);
  d1.setDate(d1.getDate() + Math.min(offsetStart, 4));
  const d2 = new Date(baseDate);
  d2.setDate(d2.getDate() + Math.min(offsetEnd, 6));
  return `${d1.toLocaleDateString('en-IN', { day: '2-digit', month: 'short' })} - ${d2.toLocaleDateString('en-IN', { day: '2-digit', month: 'short' })}`;
}

